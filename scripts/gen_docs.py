"""Generate the check reference from the catalog.

Writes docs/checks/<area>.md (every check in full), docs/checks/README.md (the index), docs/OWASP.md (coverage of
the OWASP Top 10 and API Security Top 10 lists) and the generated blocks in README.md (the headline counts, the OSI
layer table, the OWASP table and the catalog summary), each between its markers.

    python3 scripts/gen_docs.py          # write the files
    python3 scripts/gen_docs.py --check  # exit 1 if any file is out of date
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from agent_security_audit import catalog, code_audit
from agent_security_audit.checks import load_all

MODES = ("auto", "assisted", "review")
SEVERITIES = catalog.SEVERITIES
LAYERS = {1: "Physical", 2: "Data link", 3: "Network", 4: "Transport", 5: "Session", 6: "Presentation",
          7: "Application"}
AREAS = {
    "access": "Access control and Supabase row-level security",
    "api": "API abuse, input handling and rate limits",
    "auth": "Authentication and sessions",
    "browser": "Browser security headers, cookies and client code",
    "infra": "Transport, DNS, email and hosting",
    "nextjs": "Next.js and Vercel",
}
LAYER_SCOPE = {
    1: "Hosting attestations, encrypted and locked developer devices",
    2: "Deploys and dashboards used only from trusted networks",
    3: "Database reachable only from allowed networks, over SSL",
    4: "Database, cache and admin ports closed to the internet",
    5: "Sessions ended on logout and password change, token storage",
    6: "HTTPS redirect, certificate, legacy TLS and weak ciphers refused, mail transport security",
    7: ("Access control and RLS, auth, API abuse, browser headers and cookies, Next.js and Vercel settings, "
        "secrets, dependencies, DNS and email records"),
}
START = "<!-- catalog:start (generated by scripts/gen_docs.py, do not edit by hand) -->"
END = "<!-- catalog:end -->"
GENERATED = "<!-- Generated by scripts/gen_docs.py from src/agent_security_audit/catalog. Do not edit by hand. -->"


def _areas(checks):
    out = {}
    for c in checks:
        out.setdefault(c.area, []).append(c)
    return out


def _cell(text):
    return text.replace("|", "\\|")


def render_check(c, automated):
    meta = [f"Severity: {c.severity}", f"OSI layer {c.layer} ({LAYERS[c.layer]})", ", ".join(c.cwe) or "no CWE"]
    if c.asvs:
        meta.append("ASVS " + ", ".join(c.asvs))
    if c.owasp:
        meta.append("OWASP " + ", ".join(c.owasp))
    mode = c.mode + (" (proof test built in)" if c.id in automated else "")
    mode += " (code audit built in: `asa code`)" if c.id in code_audit.CHECKS else ""
    meta += [f"Mode: {mode}", "Stacks: " + ", ".join(c.stacks)]
    lines = [f"## {c.id} {c.title}", "", " · ".join(meta), "",
             "### Risk", "", c.risk, "", "### Build rule", "", c.build, "", "### Proof test", "", c.proof, "",
             "### Sources", ""]
    lines += [f"- [{s.title}]({s.url})" for s in c.sources]
    return lines


def render_area(area, checks, automated):
    lines = [GENERATED, "", f"# {area}: {AREAS.get(area, area)}", "",
             f"{len(checks)} checks. Read one in the terminal with `asa show <ID>`.", "",
             "| ID | Severity | Layer | Mode | Title |", "|---|---|---|---|---|"]
    for c in checks:
        lines.append(f"| [{c.id}](#{_anchor(c)}) | {c.severity} | L{c.layer} | {c.mode} | {_cell(c.title)} |")
    for c in checks:
        lines += [""] + render_check(c, automated)
    return "\n".join(lines) + "\n"


def _anchor(c):
    text = f"{c.id} {c.title}".lower()
    keep = "".join(ch for ch in text if ch.isalnum() or ch in " -_")
    return keep.replace(" ", "-")


def area_table(checks, link_prefix):
    lines = ["| Area | What it covers | Checks | Auto | Assisted | Review | Critical | High | Medium | Low |",
             "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for area, group in _areas(checks).items():
        modes, sev = Counter(c.mode for c in group), Counter(c.severity for c in group)
        lines.append(f"| [{area}]({link_prefix}{area}.md) | {AREAS.get(area, area)} | {len(group)} | "
                     + " | ".join(str(modes[m]) for m in MODES) + " | "
                     + " | ".join(str(sev[s]) for s in SEVERITIES) + " |")
    modes, sev = Counter(c.mode for c in checks), Counter(c.severity for c in checks)
    lines.append(f"| **Total** | | **{len(checks)}** | "
                 + " | ".join(f"**{modes[m]}**" for m in MODES) + " | "
                 + " | ".join(f"**{sev[s]}**" for s in SEVERITIES) + " |")
    return lines


def layer_table(checks):
    lines = ["| OSI layer | Checks | Auto | Assisted | Review |", "|---|---:|---:|---:|---:|"]
    for layer, name in LAYERS.items():
        group = [c for c in checks if c.layer == layer]
        modes = Counter(c.mode for c in group)
        lines.append(f"| {layer} {name} | {len(group)} | " + " | ".join(str(modes[m]) for m in MODES) + " |")
    return lines


def readme_block(checks):
    lines = [START, "", "Checks by area:", ""] + area_table(checks, "docs/checks/")
    lines += ["", "Checks by OSI layer:", ""] + layer_table(checks) + ["", END]
    return "\n".join(lines)


def coverage(checks, automated):
    """How each check is settled: a live proof test (`asa scan`), the code audit (`asa code`), both, or neither
    (guided: the agent follows the written proof steps)."""
    live = [c for c in checks if c.id in automated]
    code = [c for c in checks if c.id in code_audit.CHECKS]
    return {"total": len(checks), "live": len(live), "active": sum(c.probe == "active" for c in live),
            "code": len(code), "both": sum(c.id in automated for c in code),
            "guided": sum(c.id not in automated and c.id not in code_audit.CHECKS for c in checks)}


def headline_block(checks, automated):
    n = coverage(checks, automated)
    return (f"**{n['total']} checks, mapped to OSI layers 1 to 7:** {n['live']} live proof tests (`asa scan`; "
            f"{n['live'] - n['active']} passive, {n['active']} active), {n['code']} settled from source code "
            f"(`asa code`; {n['both']} of them also have a live test) and {n['guided']} guided checks that the agent "
            "works through with written proof steps.")


def osi_block(checks, automated):
    lines = ["| OSI layer | What is checked | Checks | Live test | From code | Guided |",
             "|---|---|---:|---:|---:|---:|"]
    for layer, name in LAYERS.items():
        n = coverage([c for c in checks if c.layer == layer], automated)
        lines.append(f"| {layer} {name} | {LAYER_SCOPE[layer]} | {n['total']} | {n['live']} | {n['code']} | "
                     f"{n['guided']} |")
    return "\n".join(lines)


OWASP_SOURCES = {
    "2021": "https://owasp.org/Top10/2021/",
    "2025": "https://owasp.org/Top10/2025/",
    "API2023": "https://owasp.org/API-Security/editions/2023/en/0x11-t10/",
}
# Limits of what any tool can see for a category, stated in the gap note next to the computed one.
OWASP_LIMITS = {
    "A04:2021": "Design flaws show up in business logic; the checks here cover named patterns, not a design review.",
    "A06:2025": "Design flaws show up in business logic; the checks here cover named patterns, not a design review.",
    "A09:2021": "Logging and alerting live on the server and in the hosting dashboard; nothing outside can see them.",
    "A09:2025": "Logging and alerting live on the server and in the hosting dashboard; nothing outside can see them.",
    "A10:2021": "A live SSRF test needs a request that makes the server fetch an address; the tool sends none.",
    "API6:2023": "Which flows are sensitive (sign-up, checkout, SMS) depends on the business; the proof is assisted.",
    "API10:2023": "Third-party responses are only visible in the code and at runtime on the server.",
}


def owasp_rows(checks, automated):
    """One row per OWASP category: (id, title, coverage counts, check ids)."""
    rows = []
    for oid, title in catalog.OWASP.items():
        group = [c for c in checks if oid in c.owasp]
        rows.append((oid, title, coverage(group, automated), [c.id for c in group]))
    return rows


def owasp_gap(oid, n):
    if n["total"] == 0:
        note = "Not covered."
    elif n["live"] == 0 and n["code"] == 0:
        note = "Guided only: no automated proof."
    elif n["live"] == 0:
        note = "No live proof test; code audit and guided steps only."
    elif n["total"] - n["guided"] < n["guided"]:
        note = "Mostly guided."
    else:
        note = ""
    limit = OWASP_LIMITS.get(oid, "")
    return " ".join(x for x in (note, limit) if x)


def _owasp_table(checks, automated, list_key, link):
    lines = ["| Category | Checks | Live test | From code | Guided | Gap |", "|---|---:|---:|---:|---:|---|"]
    for oid, title, n, ids in owasp_rows(checks, automated):
        if catalog.owasp_list(oid) != list_key:
            continue
        name = f"[{oid} {title}]({link}#{_owasp_anchor(oid)})" if link is not None else f"{oid} {title}"
        lines.append(f"| {name} | {n['total']} | {n['live']} | {n['code']} | {n['guided']} | "
                     f"{_cell(owasp_gap(oid, n)) or '-'} |")
    return lines


def _owasp_anchor(oid):
    return oid.lower().replace(":", "")


def owasp_block(checks, automated):
    lines = []
    for key, name in catalog.OWASP_LISTS.items():
        lines += [f"**{name}**", ""] + _owasp_table(checks, automated, key, "docs/OWASP.md") + [""]
    unmapped = [c.id for c in checks if not c.owasp]
    lines.append(f"{len(checks) - len(unmapped)} of {len(checks)} checks map to at least one category; the other "
                 f"{len(unmapped)} ({', '.join(unmapped)}) sit outside these lists. A count is how many checks touch a category, not a score: one category is never fully "
                 "proven by a scan.")
    return "\n".join(lines)


def render_owasp(checks, automated):
    lines = [GENERATED, "", "# OWASP coverage", "",
             ("How the catalog maps to the OWASP Top 10 (2021 and 2025) and the OWASP API Security Top 10 (2023). "
              "A check can map to several categories or to none. List the checks for one category with "
              "`asa list --owasp A01` (every list that has an A01) or `asa list --owasp A01:2021`."), "",
             ("- **Live test**: `asa scan` proves it on the running site. **From code**: `asa code` settles it from "
              "the source. **Guided**: the agent follows the written proof steps (`asa show <ID>`)."),
             ("- A count says how many checks touch a category. It is not a score, and no category is fully proven by "
              "a scan: a pass means the defense was observed working on that target at that time."), ""]
    for key, name in catalog.OWASP_LISTS.items():
        lines += [f"## {name}", "", f"Source: <{OWASP_SOURCES[key]}>", ""]
        lines += _owasp_table(checks, automated, key, "") + [""]
    lines += ["## Checks per category", ""]
    by_id = {c.id: c for c in checks}
    for oid, title, n, ids in owasp_rows(checks, automated):
        lines += [f"### {oid}", "", f"{title}. {n['total']} checks.", ""]
        for cid in ids:
            c = by_id[cid]
            how = ("live" if cid in automated else "") + (" + code" if cid in code_audit.CHECKS else "")
            how = how.strip(" +") or "guided"
            lines.append(f"- [{cid}](checks/{c.area}.md#{_anchor(c)}) {_cell(c.title)} ({how})")
        if not ids:
            lines.append("- None.")
        lines.append("")
    unmapped = [c for c in checks if not c.owasp]
    lines += ["## Outside the OWASP lists", "",
              "These checks map to no category above:", ""]
    lines += [f"- [{c.id}](checks/{c.area}.md#{_anchor(c)}) {_cell(c.title)}" for c in unmapped]
    return "\n".join(lines) + "\n"


# Other generated README blocks: (start marker, end marker, render function).
BLOCKS = (
    ("<!-- headline:start (generated by scripts/gen_docs.py, do not edit by hand) -->", "<!-- headline:end -->",
     headline_block),
    ("<!-- osi:start (generated by scripts/gen_docs.py, do not edit by hand) -->", "<!-- osi:end -->", osi_block),
    ("<!-- owasp:start (generated by scripts/gen_docs.py, do not edit by hand) -->", "<!-- owasp:end -->",
     owasp_block),
)


def _replace_block(text, start, end, body):
    if start not in text or end not in text:
        return None
    head, rest = text.split(start, 1)
    return head + start + "\n" + body + "\n" + end + rest.split(end, 1)[1]


def render_index(checks, automated):
    lines = [GENERATED, "", "# Check catalog", "",
             (f"{len(checks)} checks in {len(_areas(checks))} areas. Each check has a risk, a build rule the agent "
             "follows while writing code, a proof test that shows the defense working on the running site, and "
             "sources."), "",
             "- **auto**: `asa scan` runs the proof test and reports pass or fail with evidence.",
             "- **assisted**: the agent checks the code first, then runs a logged-in test itself if the code does not settle it.",
             ("- **review**: the proof is in the code, the hosting dashboard or a policy, so a person or the agent "
             "reads it."), "", "## By area", ""] + area_table(checks, "")
    lines += ["", "## By OSI layer", ""] + layer_table(checks)
    lines += ["", "## All checks", "", "| ID | Severity | Layer | Mode | Title |", "|---|---|---|---|---|"]
    for c in checks:
        lines.append(f"| [{c.id}]({c.area}.md#{_anchor(c)}) | {c.severity} | L{c.layer} | {c.mode} | "
                     f"{_cell(c.title)} |")
    lines += ["", f"Automated proof tests built in: {len(automated)} ("
              + ", ".join(sorted(automated)) + ")."]
    lines += ["", f"Settled from source code by `asa code`: {len(code_audit.CHECKS)} ("
              + ", ".join(sorted(code_audit.CHECKS)) + ")."]
    return "\n".join(lines) + "\n"


def outputs():
    """Map of repo-relative path to the exact text that file should hold."""
    checks = catalog.load()
    automated = {cid for cid in load_all() if catalog.by_id().get(cid)}
    files = {"docs/checks/README.md": render_index(checks, automated), "docs/OWASP.md": render_owasp(checks, automated)}
    for area, group in _areas(checks).items():
        files[f"docs/checks/{area}.md"] = render_area(area, group, automated)
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    if START in readme and END in readme:
        head, rest = readme.split(START, 1)
        tail = rest.split(END, 1)[1]
        readme = head + readme_block(checks) + tail
        for start, end, render in BLOCKS:
            readme = _replace_block(readme, start, end, render(checks, automated))
            if readme is None:
                break
        else:
            files["README.md"] = readme
    return files


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    check_only = "--check" in argv
    stale = []
    for rel, text in outputs().items():
        path = ROOT / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(rel)
        if not check_only:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if check_only and stale:
        print("out of date: " + ", ".join(stale) + " (run python3 scripts/gen_docs.py)", file=sys.stderr)
        return 1
    print(("up to date" if not stale else "wrote " + ", ".join(stale)), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
